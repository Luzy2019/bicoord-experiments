def main() -> None:
    args = parse_args()
    log_path = resolve_log_path(args.path)
    rows, skipped = load_jsonl(log_path)
    if not rows:
        raise RuntimeError(f"No JSON rows found in {log_path}")

    metrics = choose_metrics(rows, args.x, args.metrics)
    if not metrics:
        raise RuntimeError("No numeric metrics found to plot.")

    series, summary = collect_series(
        rows=rows,
        metrics=metrics,
        x_key=args.x,
        smooth_window=max(args.smooth, 1),
        max_points=args.max_points,
    )
    if not series:
        raise RuntimeError("No valid metric series found to plot.")

    out_path = pathlib.Path(args.out).expanduser().resolve() if args.out else log_path.parent / "dashboard.html"
    html = render_html(
        title=log_path.parent.name,
        log_path=log_path,
        x_key=args.x,
        smooth_window=max(args.smooth, 1),
        refresh=args.refresh,
        total_rows=len(rows),
        skipped_rows=skipped,
        series=series,
        summary=summary,
    )
    out_path.write_text(html, encoding="utf-8")
    print(f"Wrote dashboard: {out_path}")
    print(f"Metrics: {', '.join(series.keys())}")
    if args.open:
        webbrowser.open(f"file://{out_path}")


if __name__ == "__main__":
    main()
